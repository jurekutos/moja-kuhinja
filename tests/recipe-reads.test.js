import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import argon2 from 'argon2';
import request from 'supertest';
import { eq } from 'drizzle-orm';
import { openDatabase } from '../src/db/index.js';
import * as t from '../src/db/schema.js';
import { recipeReadService, readingDay } from '../src/services/recipe-reads.js';
import { recipeService } from '../src/services/recipes.js';
import { createApp } from '../src/app.js';

test('daily opens aggregate readers, respect Ljubljana month boundaries, isolate workspaces and public copies', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'moja-reads-'));
  const c = openDatabase(path.join(root, 'test.sqlite'), true);
  let app;
  try {
    c.db.insert(t.households).values([{id:1,name:'First'},{id:2,name:'Second'}]).run();
    const passwordHash = await argon2.hash('Synthetic-password');
    for (let id=1;id<=3;id++) c.db.insert(t.users).values({id,name:`Reader ${id}`,email:`reader${id}@example.test`,passwordHash}).run();
    c.db.insert(t.members).values([{userId:1,householdId:1,role:'admin'},{userId:2,householdId:1,role:'viewer'},{userId:3,householdId:2,role:'admin'}]).run();
    const user={id:1,householdId:1}, other={id:3,householdId:2};
    const recipes=recipeService(c.db);
    const sample=title=>({title,description:'',prepMinutes:0,cookMinutes:0,servings:2,notes:'',sourceType:'manual',sourceUrl:'',sourceDescription:'',status:'published',categories:[],ingredients:[],steps:[]});
    const id=recipes.save(sample('Juha'),user), hidden=recipes.save(sample('SECRET OTHER RECIPE'),other);
    const snapshot=JSON.stringify({...sample('Javna juha'),images:[],author:'Test'});
    const pub=c.db.insert(t.publications).values({householdId:1,recipeId:id,submittedBy:1,status:'approved',snapshot,createdAt:new Date().toISOString()}).returning().get().id;
    const pending=c.db.insert(t.publications).values({householdId:1,submittedBy:1,snapshot,createdAt:new Date().toISOString()}).returning().get().id;
    let now=new Date('2026-10-31T22:30:00Z');
    const reads=recipeReadService(c.db,()=>now);
    assert.equal(readingDay(now),'2026-10-31');
    assert.deepEqual(reads.record(user,id),{total:1,month:1});
    assert.deepEqual(reads.record(user,id),{total:1,month:1});
    assert.deepEqual(reads.record({id:2,householdId:1},id),{total:2,month:2});
    assert.equal(reads.record(other,id),null);
    assert.equal(reads.record(user,hidden),null);
    assert.equal(reads.record(user,pending,true),null);
    now=new Date('2026-10-31T23:30:00Z');
    assert.equal(readingDay(now),'2026-11-01');
    assert.deepEqual(reads.record(user,id),{total:3,month:1});
    reads.record(other,hidden);reads.record(other,pub,true);reads.record(user,pub,true);
    const stats=reads.statistics(user);
    assert.deepEqual(stats.totals,{total:5,month:3});
    assert.equal(stats.recipes[0].title,'Juha');
    assert.equal(reads.statistics(user,{period:'month'}).recipes[0].title,'Javna juha');
    assert.deepEqual(reads.statistics(user,{view:'workspace'}).totals,{total:3,month:1});
    assert.deepEqual(reads.statistics(user,{view:'public'}).totals,{total:2,month:2});
    assert.ok(!JSON.stringify(stats).includes('SECRET'));
    assert.deepEqual(reads.statistics(other).totals,{total:3,month:3});

    app=createApp({...c,config:{secret:'synthetic-secret-'.repeat(5),production:false,trustProxy:false,uploadDir:path.join(root,'uploads')}});
    const agent=request.agent(app);
    await agent.get('/recipes/statistics').expect(302);
    const login=await agent.get('/login');const csrf=login.text.match(/name="_csrf" value="([a-f0-9]+)"/)[1];
    await agent.post('/login').type('form').send({_csrf:csrf,email:'reader1@example.test',password:'Synthetic-password'}).expect(302);
    const before=c.db.select().from(t.recipeReads).all().length;
    await agent.get('/recipes').expect(200);
    await agent.get(`/recipes/${id}/edit`).expect(200);
    await agent.get(`/recipes/${id}/cook`).expect(200);
    await agent.get(`/recipes/${hidden}`).expect(404);
    await agent.get(`/community/${pending}`).expect(200);
    assert.equal(c.db.select().from(t.recipeReads).all().length,before);
    const detail=await agent.get(`/recipes/${id}`).expect(200);assert.match(detail.text,/Odprtja skupaj/);
    const counted=c.db.select().from(t.recipeReads).all().length;
    await agent.get(`/recipes/${id}`).expect(200);
    assert.equal(c.db.select().from(t.recipeReads).all().length,counted);
    await agent.get(`/community/${pub}`).expect(200);
    const page=await agent.get('/recipes/statistics?period=month').expect(200);
    assert.match(page.text,/Najbolj brani recepti/);assert.ok(!page.text.includes('SECRET OTHER RECIPE'));
    c.db.delete(t.recipes).where(eq(t.recipes.id,id)).run();
    assert.equal(reads.counts(user,id),null);
    assert.equal(reads.counts(user,pub,true).total>=2,true);
    assert.deepEqual(c.sqlite.pragma('foreign_key_check'),[]);
  } finally {
    app?.locals.sessionStore.close();c.sqlite.close();await fs.rm(root,{recursive:true,force:true});
  }
});
