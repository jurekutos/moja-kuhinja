import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import argon2 from 'argon2';
import sharp from 'sharp';
import request from 'supertest';
import { eq } from 'drizzle-orm';
import { openDatabase,applyMigrations } from '../src/db/index.js';
import * as t from '../src/db/schema.js';
import { createApp } from '../src/app.js';
import { publicLibraryService,versionToken } from '../src/services/public-library.js';
import { publicCookbook } from '../src/services/public-cookbook.js';
import { seedPublicLibrary } from '../src/services/seed-public-library.js';
import { recipeService } from '../src/services/recipes.js';
import { imageService } from '../src/services/images.js';
import { communityService } from '../src/services/community.js';
import { recipeCatalog } from '../src/services/recipe-catalog.js';

test('suggestions, Super Admin publishing, ordered features and independent idempotent imports',async()=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'moja-library-')),c=openDatabase(path.join(root,'test.sqlite'),true),directory=path.join(root,'uploads');let app;
  try {
    c.db.insert(t.households).values([{id:1,name:'First'},{id:2,name:'Second'}]).run();
    const password='Synthetic-password',passwordHash=await argon2.hash(password);
    c.db.insert(t.users).values([{id:1,name:'Admin',email:'admin@example.test',passwordHash,isSuperAdmin:true},{id:2,name:'Editor',email:'editor@example.test',passwordHash},{id:3,name:'Other',email:'other@example.test',passwordHash},{id:4,name:'Reader',email:'reader@example.test',passwordHash}]).run();
    c.db.insert(t.members).values([{userId:1,householdId:1,role:'admin'},{userId:2,householdId:1,role:'editor'},{userId:3,householdId:2,role:'editor'},{userId:4,householdId:1,role:'viewer'}]).run();
    const admin={id:1,name:'Admin',householdId:1,role:'admin',isSuperAdmin:true,language:'sl'},editor={id:2,name:'Editor',householdId:1,role:'editor',language:'sl'},other={id:3,name:'Other',householdId:2,role:'editor',language:'sl'};
    const service=publicLibraryService(c.db,directory),cookbook=publicCookbook(c.db),recipes=recipeService(c.db),images=imageService(c.db,directory),community=communityService(c.db,recipes,images,directory);
    app=createApp({...c,config:{secret:'synthetic-library-secret-'.repeat(4),uploadDir:directory,production:false,trustProxy:false}});
    const body={title:'Suggested soup',description:'Original suggestion',originalLanguage:'sl',prepMinutes:5,cookMinutes:10,servings:2,ingredientsJson:JSON.stringify([{name:'Water',quantity:'1.25',unit:'l',note:''}]),stepsJson:JSON.stringify(['Boil the water.']),categoryIds:[2],sourceDescription:'Original author',sourceUrl:''};
    const id=service.suggest(editor,{...body,intent:'publish'});
    const draft=service.save(admin,{...body,title:'Explicit draft',intent:'draft'});
    assert.equal(service.version(draft,'sl').status,'draft');
    assert.throws(()=>cookbook.get(draft,'sl'),{status:404});
    assert.equal(service.version(id,'sl').status,'pending');
    assert.equal(c.db.select().from(t.publications).where(eq(t.publications.id,id)).get().householdId,null);
    assert.equal(c.db.select().from(t.recipes).all().length,0);
    assert.throws(()=>cookbook.get(id,'sl'),{status:404});
    assert.throws(()=>service.save(editor,body),{status:403});
    assert.throws(()=>service.save({...editor,isSuperAdmin:true},body),{status:403});
    assert.throws(()=>service.moderate(editor,id,'sl','approved','',versionToken(service.version(id,'sl'))),{status:403});
    const stale=versionToken(service.version(id,'sl'));
    service.save(admin,{...body,title:'Edited soup',intent:'publish',version:stale},id);
    assert.throws(()=>service.save(admin,{...body,intent:'publish',version:stale},id),{status:409});
    assert.equal(cookbook.get(id,'sl').title,'Edited soup');
    assert.throws(()=>cookbook.get(id,'en'),{status:404});
    const png=await sharp({create:{width:40,height:30,channels:3,background:'#81947a'}}).png().toBuffer();
    await assert.rejects(service.upload(admin,id,'sl',[{buffer:Buffer.from('fake'),size:4,mimetype:'image/png'}],versionToken(service.version(id,'sl'))),{status:422});
    await service.upload(admin,id,'sl',[{buffer:png,size:png.length,mimetype:'image/png'}],versionToken(service.version(id,'sl')));
    await request(app).get(`/sl/community/${id}/images/0`).expect(200).expect('Content-Type',/webp/);
    const copied=await community.copy(id,editor);
    assert.equal(await community.copy(id,editor),copied);
    const catalog=recipeCatalog(c.db,recipes);
    assert.equal(catalog.list(editor,{view:'all'}).count,1);
    assert.equal(catalog.list(editor,{view:'all'}).recipes[0].publicPublicationId,id);
    assert.equal(catalog.list(editor,{view:'public'}).count,1);
    await assert.rejects(community.copy(id,{id:4,householdId:1,role:'viewer',language:'sl'}),{status:403});
    await assert.rejects(community.copy(id,editor,2),{status:403});
    const second=await community.copy(id,other);assert.notEqual(second,copied);
    assert.match(recipes.get(copied,1,2).sourceDescription,/community/);
    assert.equal(recipes.get(copied,1,2).images.length,1);
    const publicFilename=JSON.parse(service.version(id,'sl').snapshot).images[0].filename;
    await service.removeImage(admin,id,'sl',0,versionToken(service.version(id,'sl')));
    await assert.rejects(fs.access(path.join(directory,publicFilename)));
    assert.equal(recipes.get(copied,1,2).images.length,1);
    assert.throws(()=>recipes.get(copied,2,3),{status:404});
    const edited={...recipes.get(copied,1,2),title:'My independent soup',notes:'PRIVATE NOTE',categories:[],ingredients:recipes.get(copied,1,2).ingredients};
    recipes.save(edited,editor,copied);
    assert.equal(cookbook.get(id,'sl').title,'Edited soup');
    service.save(admin,{...body,title:'Public revision',intent:'publish',version:versionToken(service.version(id,'sl'))},id);
    assert.equal(recipes.get(copied,1,2).title,'My independent soup');
    const ids=[id,...['Second soup','Third soup'].map(title=>service.save(admin,{...body,title,intent:'publish'}))];
    service.feature(admin,'sl',ids.slice().reverse());
    assert.deepEqual(cookbook.featured('sl').map(r=>r.id),ids.slice().reverse());
    assert.throws(()=>service.feature(admin,'sl',[id,id,id]),{status:422});
    assert.throws(()=>service.feature(admin,'en',ids),{status:404});
    assert.equal(cookbook.list('sl',{ingredient:'WATER',maxTime:'15'}).count,3);
    assert.equal(cookbook.list('sl',{ingredient:'absent'}).count,0);
    service.moderate(admin,id,'sl','rejected','Needs work',versionToken(service.version(id,'sl')));
    assert.throws(()=>cookbook.get(id,'sl'),{status:404});
    assert.equal(cookbook.featured('sl').length,2);
    assert.equal(recipes.get(copied,1,2).title,'My independent soup');
    await request(app).get(`/sl/community/${id}/images/0`).expect(404);
    const added=seedPublicLibrary(c.db,admin,directory);assert.equal(added.added,12);
    assert.deepEqual(seedPublicLibrary(c.db,admin,directory,{publish:true}),{added:0,skipped:12});
    for(const entry of c.db.select().from(t.publicSeedEntries).all())assert.equal(service.version(entry.publicationId,'sl').status,'draft');
    assert.equal(c.db.select().from(t.recipes).all().length,2);
    applyMigrations(c.db,c.sqlite);applyMigrations(c.db,c.sqlite);
    assert.deepEqual(c.sqlite.pragma('foreign_key_check'),[]);
    const agent=request.agent(app),login=await agent.get('/sl/login');const token=login.text.match(/name="_csrf" value="([a-f0-9]+)"/)[1];
    await agent.post('/sl/login').type('form').send({_csrf:token,email:'editor@example.test',password}).expect(302);
    await agent.get('/sl/super-admin/public-recipes').expect(403);
    await agent.post('/sl/super-admin/public-recipes').send({}).expect(403);
    const suggestionForm=await agent.get('/sl/suggestions/new').expect(200);
    const suggestionToken=suggestionForm.text.match(/name="_csrf" value="([a-f0-9]+)"/)[1];
    await agent.post('/sl/suggestions').type('form').send({...body,_csrf:suggestionToken,ingredientsJson:'{}'}).expect(422);
    await agent.post('/sl/suggestions').type('form').send(body).expect(403);
    await request(app).get('/sl/suggestions/new').expect(302);
    const adminAgent=request.agent(app),adminLogin=await adminAgent.get('/sl/login');const adminToken=adminLogin.text.match(/name="_csrf" value="([a-f0-9]+)"/)[1];
    await adminAgent.post('/sl/login').type('form').send({_csrf:adminToken,email:'admin@example.test',password}).expect(302);
    await adminAgent.get('/sl/super-admin/public-recipes').expect(200);
    await adminAgent.get(`/sl/super-admin/public-recipes/${id}/edit`).expect(200);
    await adminAgent.get('/sl/').expect(200);
    const noHouse={id:3,name:'Other',householdId:null,role:'viewer',language:'sl'};
    const standalone=service.suggest(noHouse,{...body,title:'Standalone suggestion'});
    assert.equal(community.get(standalone,noHouse).status,'pending');
  }finally{app?.locals.sessionStore.close();c.sqlite.close();await fs.rm(root,{recursive:true,force:true});}
});
