import { tr } from '../i18n/index.js';
import { recipeTranslationService } from '../services/recipe-translations.js';
import { globalCatalogService } from '../services/global-catalog.js';
import { changeLanguage } from '../i18n/index.js';
import { recipeReadService } from '../services/recipe-reads.js';
import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import multer from 'multer';
import path from 'node:path';
import { authController } from '../controllers/auth.js';
import { recipeController } from '../controllers/recipes.js';
import { requireAuth, verifyCsrf, requireEditor, requireAdmin, requireModerator } from '../middleware/security.js';
import { workspaceService } from '../services/workspaces.js';
import { communityService } from '../services/community.js';
import { workspaceController } from '../controllers/workspaces.js';
import { communityController } from '../controllers/community.js';
import { recipeCatalog } from '../services/recipe-catalog.js';
import { plannerService } from '../services/planner.js';
import { plannerController } from '../controllers/planner.js';
import { MAX_IMAGE_SIZE } from '../services/images.js';
import { accountAdminRoutes } from './account-admin.js';
export function routes(db, recipes, images, config, comments) {
  const reads = recipeReadService(db);
  const translations=recipeTranslationService(db,recipes);const globalCatalog=globalCatalogService(db);
  const router = Router(); const auth = authController(db); const controller = recipeController(recipes, images, comments, recipeCatalog(db, recipes), reads, globalCatalog);
  const authorOnly = (req, res, next) => { recipes.requireAuthor(Number(req.params.id), req.user); next(); };
  const imageAuthorOnly = (req, res, next) => { const image = images.get(Number(req.params.id), req.user.householdId); recipes.requireAuthor(image.recipeId, req.user); next(); };
  const workspaces=workspaceService(db);const workspace = workspaceController(workspaces);
  const community = communityController(communityService(db, recipes, images, config.uploadDir), config, reads);
  const planner = plannerController(plannerService(db),recipeCatalog(db,recipes));
  for (const param of ['userId', 'invitationId']) router.param(param, (req, res, next, value) => {
    if (!/^\d+$/.test(value) || !Number.isSafeInteger(Number(value))) return res.status(404).render('error', { title: tr("common:s5dbe36ac6d2d"), message: tr("common:sfbd59cfbfbf2") }); next();
  });
  const limit = rateLimit({ windowMs: 15 * 60000, limit: 15, standardHeaders: 'draft-8', legacyHeaders: false, handler: (req, res) => res.status(429).render('error', { title: tr("common:s4b07fb3a8a72"), message: tr("common:s71b724676063") }) });
  router.post('/language', verifyCsrf, changeLanguage(db,config.production));
  router.get('/login', auth.loginPage);
  router.post('/login', limit, verifyCsrf, auth.login);
  router.get('/join/:token', workspace.join);
  router.post('/join/:token', limit, verifyCsrf, workspace.accept);
  router.use(requireAuth);
  router.use(accountAdminRoutes(db,workspaces,config));
  router.post('/logout', verifyCsrf, auth.logout);
  router.get('/', controller.dashboard);
  router.get('/workspace', workspace.page);
  router.post('/workspace/switch', verifyCsrf, workspace.switch);
  router.post('/workspace/invitations', verifyCsrf, requireAdmin, workspace.invite);
  router.post('/workspace/invitations/:invitationId/revoke', verifyCsrf, requireAdmin, workspace.revoke);
  router.post('/workspace/members/:userId', verifyCsrf, requireAdmin, workspace.member);
  router.get('/admin/invitations', requireModerator, workspace.platform);
  router.post('/admin/invitations', verifyCsrf, requireModerator, workspace.invitePlatform);
  router.post('/admin/invitations/:invitationId/revoke', verifyCsrf, requireModerator, workspace.revokePlatform);
  router.get('/submissions', community.mine);
  router.get('/admin/reviews', requireModerator, community.reviews);
  router.get('/community/:id', community.detail);
  router.get('/community/:id/images/:index', community.image);
  router.post('/community/:id/favorite', verifyCsrf, community.favorite);
  router.post('/community/:id/copy', verifyCsrf, requireEditor, community.copy);
  router.post('/community/:id/submit-draft',verifyCsrf,requireEditor,community.submitDraft);
  router.post('/community/:id/languages',verifyCsrf,requireEditor,community.addLanguage);
  router.post('/community/:id/review', verifyCsrf, requireModerator, community.review);
  router.get('/planner', planner.index);
  router.get('/planner/meal', requireEditor, planner.meal);
  router.post('/planner/save', verifyCsrf, requireEditor, planner.save);
  router.post('/planner/remove', verifyCsrf, requireEditor, planner.remove);
  router.post('/planner/preferences', verifyCsrf, requireEditor, planner.preferences);
  router.get('/shopping', (req,res) => res.render('coming-soon',{title:tr("common:scbb9922e21c4")}));
  router.get('/recipes', controller.list);
  router.get('/recipes/statistics', (req,res) => res.render('recipes/statistics', { title:tr("common:sd5f49afc8918"), ...reads.statistics(req.user, req.query) }));
  router.get('/recipes/new', requireEditor, controller.new);
  router.post('/recipes', verifyCsrf, requireEditor, controller.save);
  router.param('id', (req, res, next, value) => { if (!/^\d+$/.test(value) || !Number.isSafeInteger(Number(value))) return res.status(404).render('error', { title: tr("common:s5dbe36ac6d2d"), message: tr("common:s78696bf18602") }); next(); });
  router.get('/ingredients/autocomplete', (req,res)=>res.json(globalCatalog.autocomplete(req.language,req.query.q)));
  router.get('/recipes/:id/translations/:language', requireEditor, authorOnly, (req,res)=>res.render('recipes/translation',{title:tr('common:translations'),...translations.form(req.user,Number(req.params.id),req.params.language)}));
  router.post('/recipes/:id/translations/:language', verifyCsrf, requireEditor, authorOnly, (req,res)=>{translations.save(req.user,Number(req.params.id),req.params.language,req.body);req.session.flash=tr('common:translationSaved');res.redirect(`/recipes/${req.params.id}?lang=${req.params.language}`);});
  router.get('/recipes/:id', controller.detail);
  router.get('/recipes/:id/edit', requireEditor, authorOnly, controller.edit);
  router.get('/recipes/:id/cook', controller.cook);
  router.post('/recipes/:id', verifyCsrf, requireEditor, authorOnly, controller.save);
  router.post('/recipes/:id/delete', verifyCsrf, requireEditor, authorOnly, controller.remove);
  router.post('/recipes/:id/submit', verifyCsrf, requireEditor, community.submit);
  router.post('/recipes/:id/notes', verifyCsrf, controller.notes);
  router.post('/recipes/:id/favorite', verifyCsrf, controller.favorite);
  router.post('/recipes/:id/comments', verifyCsrf, controller.addComment);
  router.post('/recipes/:id/comments/:commentId/delete', verifyCsrf, controller.deleteComment);
  const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: MAX_IMAGE_SIZE, files: 5, fields: 1, parts: 6 } }).array('images', 5);
  const uploadLimit = rateLimit({ windowMs: 60000, limit: 20, standardHeaders: 'draft-8', legacyHeaders: false, handler: (req, res) => res.status(429).render('error', { title: tr("common:sd6e33d7c82e5"), message: tr("common:sb8522e1a5b2f") }) });
  // Check ownership before buffering; multipart limits bound memory, and CSRF precedes all writes.
  router.post('/recipes/:id/images', requireEditor, (req, res, next) => { recipes.requireAuthor(Number(req.params.id), req.user); next(); }, uploadLimit, upload, verifyCsrf, controller.upload);
  router.get('/images/:id', (req, res) => { const image = images.get(Number(req.params.id), req.user.householdId); res.set({ 'Cache-Control': 'private, no-store', 'X-Content-Type-Options': 'nosniff' }); res.type('webp').sendFile(path.join(config.uploadDir, req.query.size === 'small' ? image.thumbnail : image.filename)); });
  router.post('/images/:id/delete', verifyCsrf, requireEditor, imageAuthorOnly, async (req, res) => { const id = await images.remove(Number(req.params.id), req.user.householdId); req.session.flash = tr("common:s7ac8d0a6c50b"); res.redirect(`/recipes/${id}/edit#photos`); });
  router.post('/images/:id/cover', verifyCsrf, requireEditor, imageAuthorOnly, (req, res) => { const id = images.cover(Number(req.params.id), req.user.householdId); req.session.flash = tr("common:sf93dab963d74"); res.redirect(`/recipes/${id}/edit#photos`); });
  return router;
}
